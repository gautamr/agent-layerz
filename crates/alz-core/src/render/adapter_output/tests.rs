//! Spec §8.0 **Output.** and §4.3: the core emits what an adapter returns and writes every header;
//! the adapter has no way to write or change one.

use alz_adapter::{
    Bytes, Content, Descriptor, Diagnostic, Frontmatter, HeaderSource, JsonObject, JsonValue,
    LayerName, Level, MODEL_VERSION, Markdown, Output, OutputFile, SecurityItems, Source, TargetId,
    Territory, ToolVersion, ToolVersionRange,
};

use super::{Limits, emit, emit_within};
use crate::render::header::has_generated_mark;
use crate::render::tree::{FileMode, OutputPath};

const HEADER: &str = "GENERATED by agent-layerz \u{2014} DO NOT EDIT. Source: p:instructions/x.md. Edit the source and run `alz build`.";

fn toy() -> TargetId {
    TargetId::try_from("toy").expect("a target id")
}

/// The adapter `toy`, which may write the files these tests use and everything below `out/`.
fn toy_descriptor() -> Descriptor {
    let mut descriptor = Descriptor::new(
        toy(),
        MODEL_VERSION,
        ToolVersionRange::new(ToolVersion::new(1, 0, 0), ToolVersion::new(2, 0, 0)),
        "docs/toy-facts.md",
    );
    descriptor.territory = Territory::new(
        ["a.md", "b.md", "x.json", "run.sh", "a.bin"]
            .map(str::to_owned)
            .to_vec(),
        vec!["out".to_owned()],
    );
    descriptor
}

fn source() -> Source {
    Source::new(
        LayerName::try_from("p").expect("a layer name"),
        "instructions/x.md",
    )
}

fn only(file: OutputFile) -> Output {
    Output::new(vec![file], Vec::new(), alz_adapter::Coverage::default())
}

fn text_at(output: &Output, path: &str) -> String {
    let (tree, found) = emit(&toy_descriptor(), &SecurityItems::default(), output);
    assert!(!found.has_errors(), "{found}");
    let file = tree
        .get(&OutputPath::try_from(path).expect("a safe path"))
        .expect("the file is written");
    String::from_utf8(file.bytes.clone()).expect("text")
}

#[test]
fn an_adapter_cannot_set_the_header_of_a_markdown_file_without_frontmatter() {
    let forged = format!("<!-- {HEADER} -->\nNot the header.");
    let output = only(OutputFile::new(
        "a.md",
        Content::Markdown(Markdown::new(forged.clone()).with_sources(vec![source()])),
    ));
    let text = text_at(&output, "a.md");
    // The core's header is the first line; the adapter's text is body, after a blank line.
    assert_eq!(text, format!("<!-- {HEADER} -->\n\n{forged}\n"));
    assert_eq!(text.matches("GENERATED by agent-layerz").count(), 2);
    assert!(text.starts_with(&format!("<!-- {HEADER} -->\n\n")));
}

#[test]
fn an_adapter_cannot_set_the_header_of_a_markdown_file_with_frontmatter() {
    let mapping = JsonObject::from_entries(vec![(
        "# GENERATED by agent-layerz".to_owned(),
        JsonValue::Text("forged".to_owned()),
    )])
    .expect("one key");
    let output = only(OutputFile::new(
        "a.md",
        Content::Markdown(
            Markdown::new("body")
                .with_frontmatter(Frontmatter::Mapping(mapping))
                .with_sources(vec![source()]),
        ),
    ));
    let text = text_at(&output, "a.md");
    assert!(
        text.starts_with(&format!("---\n# {HEADER}\n")),
        "the core's header is the line right after the opening fence: {text}"
    );
}

#[test]
fn the_header_goes_right_after_the_opening_fence_of_a_kept_frontmatter() {
    let kept = "name: x\ndescription: y\n".to_owned();
    let output = only(OutputFile::new(
        "a.md",
        Content::Markdown(
            Markdown::new("\n\nBody.\n")
                .with_frontmatter(Frontmatter::Kept(kept))
                .with_sources(vec![source()]),
        ),
    ));
    assert_eq!(
        text_at(&output, "a.md"),
        format!("---\n# {HEADER}\nname: x\ndescription: y\n---\n\nBody.\n")
    );
}

#[test]
fn json_and_bytes_get_no_header_and_json_keys_are_in_name_order() {
    let object = JsonObject::from_entries(vec![
        ("b".to_owned(), JsonValue::Int(2)),
        ("a".to_owned(), JsonValue::Bool(true)),
    ])
    .expect("two keys");
    let output = Output::new(
        vec![
            OutputFile::new("x.json", Content::Json(JsonValue::Object(object))),
            OutputFile::new(
                "run.sh",
                Content::Bytes(Bytes::new(b"#!/bin/sh\n".to_vec()).executable(true)),
            ),
        ],
        Vec::new(),
        alz_adapter::Coverage::default(),
    );
    let (tree, found) = emit(&toy_descriptor(), &SecurityItems::default(), &output);
    assert!(!found.has_errors(), "{found}");
    let json = tree
        .get(&OutputPath::try_from("x.json").expect("a path"))
        .expect("json");
    assert_eq!(
        String::from_utf8_lossy(&json.bytes),
        "{\n  \"a\": true,\n  \"b\": 2\n}\n"
    );
    let script = tree
        .get(&OutputPath::try_from("run.sh").expect("a path"))
        .expect("script");
    assert_eq!(script.bytes, b"#!/bin/sh\n");
    assert_eq!(script.mode, FileMode::Executable);
    assert!(!has_generated_mark(&json.bytes) && !has_generated_mark(&script.bytes));
}

#[test]
fn a_file_without_sources_names_no_instructions_and_a_stub_names_the_slot_stub() {
    let none = only(OutputFile::new(
        "a.md",
        Content::Markdown(Markdown::new("x")),
    ));
    assert!(text_at(&none, "a.md").contains("Source: no instructions."));
    let stub = only(OutputFile::new(
        "b.md",
        Content::Markdown(Markdown::new("x").with_header_sources(vec![HeaderSource::SlotStub])),
    ));
    assert!(text_at(&stub, "b.md").contains("Source: slot stub."));
}

#[test]
fn a_source_that_would_end_the_comment_is_the_error_layer_and_no_file_is_written() {
    let bad = Source::new(
        LayerName::try_from("p").expect("a layer name"),
        "instructions/a-->b.md",
    );
    let output = only(OutputFile::new(
        "a.md",
        Content::Markdown(Markdown::new("x").with_sources(vec![bad])),
    ));
    let (tree, found) = emit(&toy_descriptor(), &SecurityItems::default(), &output);
    assert!(tree.is_empty());
    assert!(
        found
            .to_string()
            .starts_with("error [layer] p:instructions/a-->b.md:"),
        "{found}"
    );
}

#[test]
fn a_path_that_is_not_a_safe_relative_path_is_refused_with_the_error_target() {
    let output = only(OutputFile::new(
        "../escape.md",
        Content::Bytes(Bytes::new(Vec::new())),
    ));
    let (tree, found) = emit(&toy_descriptor(), &SecurityItems::default(), &output);
    assert!(tree.is_empty());
    assert!(found.has_errors());
    assert!(
        found
            .to_string()
            .starts_with("error [target] the 'toy' adapter"),
        "{found}"
    );
}

#[test]
fn a_diagnostic_code_that_is_not_an_adapter_code_is_refused_with_the_error_target() {
    let output = Output::new(
        Vec::new(),
        vec![Diagnostic::new(Level::Warning, "yaml", "forged")],
        alz_adapter::Coverage::default(),
    );
    let (_, found) = emit(&toy_descriptor(), &SecurityItems::default(), &output);
    assert!(found.has_errors());
    assert!(found.to_string().contains("[target]"), "{found}");
}

#[test]
fn an_adapter_diagnostic_keeps_its_level_code_place_and_a_stripped_message() {
    let output = Output::new(
        Vec::new(),
        vec![Diagnostic::new(Level::Warning, "tool-scope", "a\u{202e}b\nc").about(source())],
        alz_adapter::Coverage::default(),
    );
    let (_, found) = emit(&toy_descriptor(), &SecurityItems::default(), &output);
    assert_eq!(
        found.to_string(),
        "warning [tool-scope] p:instructions/x.md: abc\n"
    );
}

#[test]
fn two_files_at_one_path_are_the_error_collision_and_the_first_stays() {
    let output = Output::new(
        vec![
            OutputFile::new("a.bin", Content::Bytes(Bytes::new(vec![1]))),
            OutputFile::new("a.bin", Content::Bytes(Bytes::new(vec![2]))),
        ],
        Vec::new(),
        alz_adapter::Coverage::default(),
    );
    let (tree, found) = emit(&toy_descriptor(), &SecurityItems::default(), &output);
    assert!(
        found.to_string().starts_with("error [collision]"),
        "{found}"
    );
    let kept = tree
        .get(&OutputPath::try_from("a.bin").expect("a path"))
        .expect("the first");
    assert_eq!(kept.bytes, [1]);
}

fn bytes_file(path: &str, size: usize) -> OutputFile {
    OutputFile::new(path, Content::Bytes(Bytes::new(vec![0; size])))
}

fn within(limits: &Limits, files: Vec<OutputFile>) -> (crate::render::tree::FileTree, String) {
    let output = Output::new(files, Vec::new(), alz_adapter::Coverage::default());
    let (tree, found) = emit_within(
        limits,
        &toy_descriptor(),
        &SecurityItems::default(),
        &output,
    );
    (tree, found.to_string())
}

#[test]
fn the_limits_of_the_spec_are_10000_files_16_mib_a_file_and_256_mib_in_all() {
    assert_eq!(
        Limits::SPEC,
        Limits::new(10_000, 16 * 1024 * 1024, 256 * 1024 * 1024)
    );
    assert!(Limits::SPEC.check_file(16_777_216).is_ok());
    assert!(Limits::SPEC.check_file(16_777_217).is_err());
    assert!(Limits::SPEC.check_total([268_435_456].into_iter()).is_ok());
    assert!(
        Limits::SPEC
            .check_total([268_435_456, 1].into_iter())
            .is_err()
    );
}

#[test]
fn more_files_than_the_limit_write_nothing() {
    let limits = Limits::new(2, 100, 100);
    let (tree, text) = within(
        &limits,
        vec![
            bytes_file("a.md", 0),
            bytes_file("b.md", 0),
            bytes_file("a.bin", 0),
        ],
    );
    assert!(tree.is_empty());
    assert_eq!(
        text,
        "error [target] the 'toy' adapter returned output that is refused: it returned 3 files, more than the limit of 2\n"
    );
}

#[test]
fn a_file_over_the_limit_is_left_out_and_one_at_the_limit_is_kept() {
    let limits = Limits::new(10, 4, 100);
    let (tree, text) = within(&limits, vec![bytes_file("a.md", 4), bytes_file("b.md", 5)]);
    assert_eq!(tree.len(), 1);
    assert_eq!(
        text,
        "error [target] the 'toy' adapter returned output that is refused: the file b.md is too large: it holds 5 bytes, more than the limit of 4 bytes for a file\n"
    );
}

#[test]
fn files_that_are_each_within_the_limit_but_over_it_in_all_are_the_error_target() {
    let limits = Limits::new(10, 4, 7);
    let (_, within_limit) = within(&limits, vec![bytes_file("a.md", 4), bytes_file("b.md", 3)]);
    assert!(within_limit.is_empty(), "{within_limit}");
    let (_, text) = within(&limits, vec![bytes_file("a.md", 4), bytes_file("b.md", 4)]);
    assert_eq!(
        text,
        "error [target] the 'toy' adapter returned output that is refused: the files hold 8 bytes in all, more than the limit of 7 bytes\n"
    );
}

fn adapter_named(id: &str) -> Descriptor {
    let mut descriptor = toy_descriptor();
    descriptor.target = TargetId::try_from(id).expect("a target id");
    descriptor
}

fn code_from(descriptor: &Descriptor, code: &str) -> String {
    let output = Output::new(
        Vec::new(),
        vec![Diagnostic::new(Level::Error, code, "text")],
        alz_adapter::Coverage::default(),
    );
    emit(descriptor, &SecurityItems::default(), &output)
        .1
        .to_string()
}

#[test]
fn an_own_code_of_the_adapter_is_accepted_and_the_same_code_from_another_adapter_is_not() {
    assert_eq!(
        code_from(&adapter_named("claude"), "claude-agent"),
        "error [claude-agent] text\n"
    );
    assert!(
        code_from(&adapter_named("toy"), "claude-agent").starts_with(
            "error [target] the 'toy' adapter returned the diagnostic code claude-agent"
        ),
    );
}

#[test]
fn a_code_of_the_core_is_never_an_adapters_own_code() {
    // An adapter with the id `account` cannot raise `account-home`, which the tables give to the
    // core, although the code starts with the adapter's id and `-`.
    assert!(
        code_from(&adapter_named("account"), "account-home")
            .starts_with("error [target] the 'account' adapter returned the diagnostic code")
    );
}
