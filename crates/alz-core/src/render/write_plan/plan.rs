//! The pure decision of the writer (spec §4.3): from what a build makes, what is on disk and the
//! previous lock, which files are created, updated and deleted, and which paths are collisions.

use std::fmt;
use std::sync::LazyLock;

use crate::lock::{FileHash, Lock};
use crate::path::SafeRelPath;
use crate::render::gitignore::{Generated, synced};
use crate::render::header::has_generated_mark;
use crate::render::protected::Protected;
use crate::render::tree::{FileMode, FileTree, GeneratedFile, OutputPath};
use crate::render::write_plan::disk::{Disk, MAX_COMPARED_BYTES, Observed};
use crate::untrusted_text::Stripped;

/// The path of the lock, the last file the writer writes.
static LOCK_PATH: LazyLock<SafeRelPath> =
    LazyLock::new(|| SafeRelPath::try_from("layer.lock").expect("a constant safe path"));
/// The path of the ignore file that holds the managed block.
static GITIGNORE_PATH: LazyLock<SafeRelPath> =
    LazyLock::new(|| SafeRelPath::try_from(".gitignore").expect("a constant safe path"));

/// The path of `layer.lock`, which the writer writes last.
#[must_use]
pub fn lock_path() -> &'static SafeRelPath {
    &LOCK_PATH
}

/// The path of `.gitignore`, which holds the managed block.
#[must_use]
pub fn gitignore_path() -> &'static SafeRelPath {
    &GITIGNORE_PATH
}

/// One thing the writer does to a generated file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Change {
    /// A path the build makes that does not exist.
    Create {
        /// Where.
        path: OutputPath,
        /// What to write.
        file: GeneratedFile,
    },
    /// A path the build makes that is alz's own and whose bytes or executable bit differ.
    Update {
        /// Where.
        path: OutputPath,
        /// What to write.
        file: GeneratedFile,
    },
    /// A path the previous lock lists, that the build no longer makes and that is alz's own.
    Delete {
        /// Where.
        path: SafeRelPath,
    },
}

impl Change {
    /// The path the change is about.
    #[must_use]
    pub fn path(&self) -> &SafeRelPath {
        match self {
            Self::Create { path, .. } | Self::Update { path, .. } => path.as_safe(),
            Self::Delete { path } => path,
        }
    }
}

/// Why a path is a collision. [`Display`](fmt::Display) is the text of §4.3 and §10.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CollisionReason {
    /// It exists and alz did not write it: no generated mark, and no entry of the previous lock
    /// whose hash matches.
    NotGenerated,
    /// It is a link, or lies under one.
    Link,
    /// It is a folder, a FIFO, a device or another entry that is not a regular file.
    NotRegular,
    /// It is longer than the writer compares.
    TooLarge,
    /// A file in the same folder is spelled differently and is the same file on a file system
    /// that ignores case.
    DiffersOnlyInCase(SafeRelPath),
    /// It must be read as text and is not valid UTF-8.
    NotText,
}

impl fmt::Display for CollisionReason {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::NotGenerated => formatter.write_str(
                "exists and was not generated by agent-layerz; move it into a layer, or rerun \
                 with --adopt to move it into the repo layer",
            ),
            Self::Link => {
                formatter.write_str("is a link or lies under one; alz never writes through a link")
            }
            Self::NotRegular => formatter.write_str("is not a regular file"),
            Self::TooLarge => write!(
                formatter,
                "is larger than {MAX_COMPARED_BYTES} bytes, which alz does not compare"
            ),
            Self::DiffersOnlyInCase(other) => write!(
                formatter,
                "differs only in case from {}, which is not generated by agent-layerz",
                Stripped::from_untrusted(other.as_str())
            ),
            Self::NotText => formatter.write_str("is not valid UTF-8 text"),
        }
    }
}

/// A path the writer refuses to touch.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Collision {
    path: SafeRelPath,
    reason: CollisionReason,
}

impl Collision {
    /// The path.
    #[must_use]
    pub const fn path(&self) -> &SafeRelPath {
        &self.path
    }

    /// Why.
    #[must_use]
    pub const fn reason(&self) -> &CollisionReason {
        &self.reason
    }
}

/// What the writer would do: the plan of one build against one observation of the repository.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WritePlan {
    changes: Vec<Change>,
    collisions: Vec<Collision>,
    gitignore: Option<Vec<u8>>,
    lock_text: String,
    lock_changed: bool,
}

impl WritePlan {
    /// The files to create and update, in path order, then the files to delete, in path order.
    #[must_use]
    pub fn changes(&self) -> &[Change] {
        &self.changes
    }

    /// The paths the writer refuses to touch, in path order.
    #[must_use]
    pub fn collisions(&self) -> &[Collision] {
        &self.collisions
    }

    /// The text of the lock this build makes.
    #[must_use]
    pub fn lock_text(&self) -> &str {
        &self.lock_text
    }

    /// Whether `layer.lock` differs from `lock_text`.
    #[must_use]
    pub const fn lock_changed(&self) -> bool {
        self.lock_changed
    }

    /// Whether `.gitignore` changes.
    #[must_use]
    pub const fn gitignore_changed(&self) -> bool {
        self.gitignore.is_some()
    }

    /// Whether the plan changes nothing and refuses nothing.
    #[must_use]
    pub fn is_settled(&self) -> bool {
        self.changes.is_empty()
            && self.collisions.is_empty()
            && self.gitignore.is_none()
            && !self.lock_changed
    }

    /// The plan as something that can be applied, which only a plan without a collision is.
    ///
    /// # Errors
    ///
    /// Every collision, when there is one: nothing is written then (§4.3 "Writing").
    pub fn into_clear(self) -> Result<ClearPlan, Vec<Collision>> {
        if self.collisions.is_empty() {
            Ok(ClearPlan {
                changes: self.changes,
                gitignore: self.gitignore,
                lock: self.lock_changed.then_some(self.lock_text),
            })
        } else {
            Err(self.collisions)
        }
    }
}

/// A plan with no collision: the only thing the writer applies.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ClearPlan {
    changes: Vec<Change>,
    gitignore: Option<Vec<u8>>,
    lock: Option<String>,
}

impl ClearPlan {
    /// The changes, creates and updates first.
    #[must_use]
    pub fn changes(&self) -> &[Change] {
        &self.changes
    }

    /// The new bytes of `.gitignore`, when it changes.
    #[must_use]
    pub fn gitignore(&self) -> Option<&[u8]> {
        self.gitignore.as_deref()
    }

    /// The new text of `layer.lock`, when it changes.
    #[must_use]
    pub fn lock(&self) -> Option<&str> {
        self.lock.as_deref()
    }
}

/// Plans the writes of a build.
///
/// A file is alz's own when it carries the generated mark, or when `previous` lists it and its
/// bytes hash to what `previous` recorded; `previous` alone never makes a file alz's own.
/// Only alz's own files are updated or deleted, a link or a path under one is never alz's own, and
/// a protected path is never deleted.
#[must_use]
pub fn plan_writes(
    tree: &FileTree,
    lock: &Lock,
    previous: Option<&Lock>,
    disk: &Disk,
    protected: &Protected,
    generated: Generated,
) -> WritePlan {
    let recorded = |path: &SafeRelPath| previous.and_then(|lock| lock.files.get(path));
    let (made, made_collisions) = split(
        tree.iter()
            .map(|(path, file)| make(path, file, disk, previous)),
    );
    let removed = previous
        .into_iter()
        .flat_map(|lock| lock.files.iter())
        .filter(|(path, _)| !is_reserved(path) && !claimed(tree, path) && !covered(protected, path))
        .filter_map(|(path, hash)| remove(path, hash, disk));
    let unmade_collisions = disk
        .managed()
        .filter(|path| !is_reserved(path) && !claimed(tree, path) && !covered(protected, path))
        .filter_map(|path| unmade(path, recorded(path), disk));
    let lock_text = lock.emit();
    let lock_path_state = disk.get(&LOCK_PATH);
    let lock_collision = refusal(&LOCK_PATH, lock_path_state);
    let lock_changed = lock_collision.is_none()
        && !matches!(lock_path_state, Observed::Regular { bytes, .. } if bytes == lock_text.as_bytes());
    let (gitignore, gitignore_collision) = gitignore_of(tree, disk, generated);
    let mut collisions: Vec<Collision> = made_collisions
        .into_iter()
        .chain(unmade_collisions)
        .chain(lock_collision)
        .chain(gitignore_collision)
        .collect();
    collisions.sort_by(|left, right| left.path.cmp(&right.path));
    WritePlan {
        changes: made.into_iter().chain(removed).collect(),
        collisions,
        gitignore,
        lock_text,
        lock_changed,
    }
}

/// Successes and refusals, each in order.
fn split<T, E>(results: impl Iterator<Item = Result<Option<T>, E>>) -> (Vec<T>, Vec<E>) {
    results.fold(
        (Vec::new(), Vec::new()),
        |(mut done, mut refused), result| {
            match result {
                Ok(Some(item)) => done.push(item),
                Ok(None) => {}
                Err(refusal) => refused.push(refusal),
            }
            (done, refused)
        },
    )
}

/// Whether the file is alz's own: the mark, or the hash the lock recorded.
fn owns(bytes: &[u8], recorded: Option<&FileHash>) -> bool {
    has_generated_mark(bytes) || recorded.is_some_and(|hash| *hash == FileHash::of(bytes))
}

/// The refusal for an entry that is no regular file, or `None` for a regular file or nothing.
fn refusal(path: &SafeRelPath, observed: &Observed) -> Option<Collision> {
    let reason = match observed {
        Observed::Absent | Observed::Regular { .. } => return None,
        Observed::Link => CollisionReason::Link,
        Observed::NotRegular => CollisionReason::NotRegular,
        Observed::TooLarge => CollisionReason::TooLarge,
    };
    Some(Collision {
        path: path.clone(),
        reason,
    })
}

fn collision(path: &SafeRelPath, reason: CollisionReason) -> Collision {
    Collision {
        path: path.clone(),
        reason,
    }
}

/// What to do about a path the build makes.
fn make(
    path: &OutputPath,
    file: &GeneratedFile,
    disk: &Disk,
    previous: Option<&Lock>,
) -> Result<Option<Change>, Collision> {
    let safe = path.as_safe();
    let listed_before =
        |other: &SafeRelPath| previous.is_some_and(|lock| lock.files.contains_key(other));
    if let Some(other) = disk.variant_of(safe).filter(|other| !listed_before(other)) {
        return Err(collision(
            safe,
            CollisionReason::DiffersOnlyInCase(other.clone()),
        ));
    }
    match disk.get(safe) {
        Observed::Absent => Ok(Some(Change::Create {
            path: path.clone(),
            file: file.clone(),
        })),
        Observed::Regular { bytes, executable } => {
            let recorded = previous.and_then(|lock| lock.files.get(safe));
            if !owns(bytes, recorded) {
                Err(collision(safe, CollisionReason::NotGenerated))
            } else if *bytes == file.bytes && *executable == (file.mode == FileMode::Executable) {
                Ok(None)
            } else {
                Ok(Some(Change::Update {
                    path: path.clone(),
                    file: file.clone(),
                }))
            }
        }
        Observed::Link | Observed::NotRegular | Observed::TooLarge => {
            Err(refusal(safe, disk.get(safe))
                .unwrap_or_else(|| collision(safe, CollisionReason::NotRegular)))
        }
    }
}

/// What to do about a path the previous lock lists and the build no longer makes: delete it when
/// it is alz's own, leave it alone otherwise.
fn remove(path: &SafeRelPath, hash: &FileHash, disk: &Disk) -> Option<Change> {
    match disk.get(path) {
        Observed::Regular { bytes, .. } if owns(bytes, Some(hash)) => {
            Some(Change::Delete { path: path.clone() })
        }
        Observed::Absent
        | Observed::Regular { .. }
        | Observed::Link
        | Observed::NotRegular
        | Observed::TooLarge => None,
    }
}

/// What a file in a managed folder that the build does not make is: a collision unless it is
/// alz's own.
fn unmade(path: &SafeRelPath, recorded: Option<&FileHash>, disk: &Disk) -> Option<Collision> {
    let observed = disk.get(path);
    refusal(path, observed).or_else(|| match observed {
        Observed::Regular { bytes, .. } if !owns(bytes, recorded) => {
            Some(collision(path, CollisionReason::NotGenerated))
        }
        Observed::Regular { .. }
        | Observed::Absent
        | Observed::Link
        | Observed::NotRegular
        | Observed::TooLarge => None,
    })
}

/// The new bytes of `.gitignore` when they differ, and the collision when the file cannot be
/// read as text.
fn gitignore_of(
    tree: &FileTree,
    disk: &Disk,
    generated: Generated,
) -> (Option<Vec<u8>>, Option<Collision>) {
    let observed = disk.get(&GITIGNORE_PATH);
    if let Some(refused) = refusal(&GITIGNORE_PATH, observed) {
        return (None, Some(refused));
    }
    let current = match observed {
        Observed::Regular { bytes, .. } => match std::str::from_utf8(bytes) {
            Ok(text) => text,
            Err(_) => {
                return (
                    None,
                    Some(collision(&GITIGNORE_PATH, CollisionReason::NotText)),
                );
            }
        },
        Observed::Absent | Observed::Link | Observed::NotRegular | Observed::TooLarge => "",
    };
    let next = synced(current, tree, generated);
    let changed = next != current;
    (changed.then(|| next.into_bytes()), None)
}

fn output(path: &SafeRelPath) -> Option<OutputPath> {
    OutputPath::try_from(path.clone()).ok()
}

/// Whether the tree makes this path, or one a file system that ignores case counts as the same.
fn claimed(tree: &FileTree, path: &SafeRelPath) -> bool {
    output(path).is_some_and(|path| tree.claim_of(&path).is_some())
}

fn covered(protected: &Protected, path: &SafeRelPath) -> bool {
    output(path).is_some_and(|path| protected.covers(&path))
}

/// The files the writer handles on its own rules.
fn is_reserved(path: &SafeRelPath) -> bool {
    *path == *LOCK_PATH || *path == *GITIGNORE_PATH
}
