fn two_sources() -> Sources {
    Sources::new(
        file(label("a", Some("1")), "b"),
        [file(label("c", None), "d")],
    )
}

const COMMENT: &str = "# GENERATED by agent-layerz \u{2014} DO NOT EDIT. Source: a@1:b + c:d. Edit the source and run `alz build`.";

#[test]
fn the_comment_goes_in_as_the_first_line_of_the_frontmatter() {
    for (text, expected) in [
        (
            "---\nname: x\n---\nbody\n",
            format!("---\n{COMMENT}\nname: x\n---\nbody\n"),
        ),
        ("---\n---\n", format!("---\n{COMMENT}\n---\n")),
        (
            "---\n# old comment\nname: x\n---\n\nbody \u{fc}\n",
            format!("---\n{COMMENT}\n# old comment\nname: x\n---\n\nbody \u{fc}\n"),
        ),
        ("---\nname: x\n", format!("---\n{COMMENT}\nname: x\n")),
    ] {
        assert_eq!(
            insert_frontmatter_header(text, &two_sources()),
            Ok(expected),
            "{text:?}"
        );
    }
}

#[test]
fn windows_line_endings_become_line_feeds_in_the_whole_file_as_in_the_reference() {
    assert_eq!(
        insert_frontmatter_header(
            "---\r\nname: x\r\ndescription: y\r\n---\r\nbody\r\n",
            &two_sources()
        ),
        Ok(format!(
            "---\n{COMMENT}\nname: x\ndescription: y\n---\nbody\n"
        ))
    );
    assert_eq!(
        insert_frontmatter_header("---\nname: x\n---\nline\r\nline2\r\n", &two_sources()),
        Ok(format!("---\n{COMMENT}\nname: x\n---\nline\nline2\n"))
    );
}

#[test]
fn a_file_without_frontmatter_takes_no_header() {
    for text in [
        "",
        "body\n",
        "--- \nname: x\n---\n",
        "\n---\nname: x\n---\n",
        "---",
    ] {
        assert_eq!(
            insert_frontmatter_header(text, &two_sources()),
            Err(NoFrontmatter),
            "{text:?}"
        );
    }
}

#[test]
fn text_that_could_leave_its_comment_or_hide_is_refused() {
    let name = LayerName::try_from("acme").expect("a name");
    for revision in ["1\n2", "1\u{85}", "a\u{202e}b", "x\u{2028}y"] {
        assert_eq!(
            LayerLabel::new(&name, Some(revision)),
            Err(SourceRefError::Unprintable),
            "{revision:?}"
        );
    }
    assert_eq!(
        LayerLabel::new(&name, Some("a-->b")),
        Err(SourceRefError::ClosesComment)
    );
    let ok = label("acme", Some("1.0.0"));
    for path in ["a\nb.md", "x\u{200b}.md", "a\u{7f}"] {
        let safe = SafeRelPath::try_from(path).expect("a safe path");
        assert_eq!(
            SourceRef::layer_file(ok.clone(), safe),
            Err(SourceRefError::Unprintable),
            "{path:?}"
        );
    }
    let closing = SafeRelPath::try_from("a-->b.md").expect("a safe path");
    assert_eq!(
        SourceRef::layer_file(ok.clone(), closing),
        Err(SourceRefError::ClosesComment)
    );
    let dashes = SafeRelPath::try_from("a--b -- c.md").expect("a safe path");
    assert!(SourceRef::layer_file(ok, dashes).is_ok());
}

#[test]
fn the_generated_mark_is_found_in_the_first_kilobyte_current_or_legacy() {
    assert!(has_generated_mark(
        html_header(&Sources::single(SourceRef::SlotStub)).as_bytes()
    ));
    assert!(has_generated_mark(
        b"<!-- GENERATED by agent-layers \xe2\x80\x94 DO NOT EDIT. -->"
    ));
    assert!(!has_generated_mark(b"# hand written\n"));
    assert!(!has_generated_mark(b""));
    let late = [vec![b'x'; 1024], b"GENERATED by agent-layerz".to_vec()].concat();
    assert!(
        !has_generated_mark(&late),
        "the mark must be near the start"
    );
    let edge = [vec![b'x'; 1024 - 25], b"GENERATED by agent-layerz".to_vec()].concat();
    assert!(has_generated_mark(&edge));
}

proptest! {
    /// The header round trip: a header built from sources is recognised as generated, names
    /// every source in order, and inserting it keeps the rest of a file as it was.
    #[test]
    fn a_header_names_every_source_in_order_and_is_recognised(
        names in proptest::collection::vec("[a-z][a-z0-9]{0,6}", 1..4),
        paths in proptest::collection::vec("[a-z]{1,5}/[a-zA-Z0-9 ._\u{e9}-]{1,8}", 1..4),
        body in "[ -~\n\u{e9}]{0,40}",
    ) {
        let refs: Vec<SourceRef> = names
            .iter()
            .zip(&paths)
            .filter_map(|(name, path)| {
                let name = LayerName::try_from(name.as_str()).ok()?;
                let label = LayerLabel::new(&name, Some("1.0.0")).ok()?;
                SourceRef::layer_file(label, SafeRelPath::try_from(path.as_str()).ok()?).ok()
            })
            .collect();
        let Some((first, rest)) = refs.split_first() else { return Ok(()) };
        let list = Sources::new(first.clone(), rest.to_vec());
        let text = header_text(&list);
        prop_assert!(has_generated_mark(text.as_bytes()));
        let joined = refs.iter().map(ToString::to_string).collect::<Vec<_>>().join(" + ");
        let expected = format!("Source: {joined}. Edit");
        prop_assert!(text.contains(&expected));
        let original = format!("---\nname: x\n---\n{body}");
        let inserted = insert_frontmatter_header(&original, &list);
        prop_assert_eq!(
            inserted,
            Ok(format!("---\n{}\nname: x\n---\n{body}", frontmatter_header(&list)))
        );
    }
}
