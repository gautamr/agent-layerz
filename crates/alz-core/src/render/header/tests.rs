use proptest::prelude::{prop_assert, prop_assert_eq, proptest};

use super::{
    LayerLabel, NoFrontmatter, SourceRef, SourceRefError, Sources, frontmatter_header,
    has_generated_mark, header_text, html_header, insert_frontmatter_header,
};
use crate::layer::LayerName;
use crate::path::SafeRelPath;
