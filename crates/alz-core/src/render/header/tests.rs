fn label(name: &str, revision: Option<&str>) -> LayerLabel {
    LayerLabel::new(&LayerName::try_from(name).expect("a name"), revision).expect("a label")
}

fn file(label: LayerLabel, path: &str) -> SourceRef {
    SourceRef::layer_file(label, SafeRelPath::try_from(path).expect("a path")).expect("a source")
}

// The strings below are what the reference's `headerText`, `htmlHeader` and
// `insertFrontmatterComment` return for the same sources: the first three appear in
// fixtures/02-instructions and 03-agent-overlay; the rest were produced by running the
// reference (TASK-55.6.2).

#[test]
fn the_html_header_is_the_one_in_the_instructions_fixture() {
    let list = Sources::new(
        file(label("personal", Some("1.0.0")), "instructions/00-core.md"),
        [
            file(label("acme", None), "instructions/10-domain.md"),
            file(label("shop-api", None), "instructions/50-repo.md"),
        ],
    );
    assert_eq!(
        html_header(&list),
        "<!-- GENERATED by agent-layerz \u{2014} DO NOT EDIT. Source: personal@1.0.0:instructions/00-core.md + acme:instructions/10-domain.md + shop-api:instructions/50-repo.md. Edit the source and run `alz build`. -->"
    );
}

