// One layer of agents, built here.

fn one_layer(files: &[(&'static str, &'static str)]) -> ClaudeFiles {
    ClaudeFiles::of(&model(
        &[Layer {
            yaml: "name: only\nkind: repo\nvisibility: private\n",
            files: Box::leak(files.to_vec().into_boxed_slice()),
        }],
        "",
    ))
}

fn text_of(files: &ClaudeFiles, name: &str) -> String {
    String::from_utf8(
        files
            .tree()
            .get(&path(name))
            .expect("a made file")
            .bytes
            .clone(),
    )
    .expect("text")
}

#[test]
fn native_fields_keep_source_order_after_the_fixed_fields_not_name_order() {
    let files = one_layer(&[(
        "agents/a.md",
        "---\nname: a\ndescription: d\nclaude:\n  maxTurns: 9\n  effort: high\n  color: blue\n---\nBody\n",
    )]);
    assert_eq!(
        text_of(&files, ".claude/agents/a.md"),
        "---\n# GENERATED by agent-layerz \u{2014} DO NOT EDIT. Source: only:agents/a.md. Edit the source and run `alz build`.\nname: a\ndescription: d\nmaxTurns: 9\neffort: high\ncolor: blue\n---\n\nBody\n"
    );
}

#[test]
fn an_empty_tools_list_and_a_non_claude_model_are_the_error_claude_agent() {
    let empty = one_layer(&[(
        "agents/a.md",
        "---\nname: a\ndescription: d\ntools: []\n---\nBody\n",
    )]);
    assert_eq!(
        lines(empty.diagnostics()),
        [
            "error [claude-agent] only:agents/a.md: agent a has an empty tools list, which Claude reads as \"all tools\""
        ]
    );
    assert!(empty.tree().is_empty());
    let bad_model = ClaudeFiles::of(&model(
        &[Layer {
            yaml: "name: only\nkind: repo\nvisibility: private\n",
            files: &[
                (
                    "agents/a.md",
                    "---\nname: a\ndescription: d\nmodel: big\n---\nBody\n",
                ),
                ("models.yaml", "aliases:\n  big:\n    claude: gpt-4\n"),
            ],
        }],
        "",
    ));
    assert_eq!(
        lines(bad_model.diagnostics()),
        ["error [claude-agent] only:agents/a.md: agent a: 'gpt-4' is not a Claude model value"]
    );
}

#[test]
fn tools_are_native_names_without_duplicates_and_a_scope_is_a_warning() {
    let files = one_layer(&[(
        "agents/a.md",
        "---\nname: a\ndescription: d\ntools: [read, bash:mise run *, bash, mcp__x__y]\n---\n",
    )]);
    assert!(text_of(&files, ".claude/agents/a.md").contains("\ntools: Read, Bash, mcp__x__y\n"));
    assert_eq!(files.diagnostics().warning_count(), 1);
}

