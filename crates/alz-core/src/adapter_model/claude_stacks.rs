fn agent_files() -> impl Strategy<Value = Vec<(usize, Vec<usize>)>> {
    proptest::collection::vec(
        (0_usize..4, proptest::collection::vec(0_usize..3, 0..4)),
        0..6,
    )
}

proptest! {
    #[test]
    fn rendering_is_deterministic_and_every_output_is_a_path_of_the_tree(specs in agent_files()) {
        const NAMES: [&str; 4] = ["alpha", "beta", "gamma", "delta"];
        const TOOLS: [&str; 3] = ["read", "grep", "bash"];
        let files: Vec<(String, String)> = specs
            .iter()
            .map(|(name, tools)| {
                let tools = tools.iter().map(|tool| TOOLS[*tool]).collect::<Vec<_>>().join(", ");
                (
                    format!("agents/{}.md", NAMES[*name]),
                    format!("---\nname: {}\ndescription: d\ntools: [{tools}]\n---\nBody\n", NAMES[*name]),
                )
            })
            .collect();
        let unique: std::collections::BTreeMap<&str, &str> =
            files.iter().map(|(path, text)| (path.as_str(), text.as_str())).collect();
        let leaked: Vec<(&'static str, &'static str)> = unique
            .iter()
            .map(|(path, text)| (&*Box::leak(path.to_string().into_boxed_str()), &*Box::leak(text.to_string().into_boxed_str())))
            .collect();
        let layer = Layer { yaml: "name: only\nkind: repo\nvisibility: private\n", files: Box::leak(leaked.clone().into_boxed_slice()) };
        let merged = model(&[layer], "");
        let first = files_of(&merged);
        let second = files_of(&merged);
        prop_assert_eq!(&first, &second);
        let rendered = first.tree().len() + first.diagnostics().error_count();
        prop_assert_eq!(rendered, leaked.len());
        prop_assert_eq!(first.tree().paths().count(), first.tree().len());
    }
}

/// The `SKILL.md` of a layer reaches the output as the layer wrote it, in line feeds, with the
/// core's header as the first line of its frontmatter (§4.3, §8.1): the same bytes as inserting the
/// header into the text, for every text the layer parser accepts.
fn skill_md_written(text: &str) -> (String, String) {
    use alz_adapter::{Adapter, Context, LayerName, Model, Skill, SkillFile, Source};

    use crate::render::header::{Sources, insert_frontmatter_header};
    use crate::render::sources::refs_of_sources;

    let source = Source::new(
        LayerName::try_from("personal").expect("a layer name"),
        "skills/glossary/SKILL.md",
    );
    let mut skill = Skill::new(
        "glossary",
        vec![SkillFile::new("SKILL.md", text.as_bytes().to_vec(), false)],
    );
    skill.sources = vec![source.clone()];
    let mut model = Model::new(crate::target::claude().clone());
    model.skills = vec![skill];
    let output = ClaudeAdapter::new().render(&model, &Context::default());
    let (tree, found) = crate::render::adapter_output::emit(
        ClaudeAdapter::new().descriptor(),
        &model.security,
        &output,
    );
    assert!(!found.has_errors(), "{found}");
    let refs = refs_of_sources(&[source]).expect("a source that stands in a comment");
    let mut refs = refs.into_iter();
    let first = refs.next().expect("one source");
    let expected = insert_frontmatter_header(text, &Sources::new(first, refs)).expect("a block");
    let written = tree
        .get(&path(".claude/skills/glossary/SKILL.md"))
        .expect("the skill file");
    (
        String::from_utf8_lossy(&written.bytes).into_owned(),
        expected,
    )
}

#[test]
fn a_skill_md_is_kept_byte_for_byte_with_the_header_right_after_the_opening_fence() {
    let text =
        "---\r\nname: glossary\r\ndescription: \"Terms\"   \r\n---\r\n\r\n# Glossary\r\nBody.\r\n";
    let (written, expected) = skill_md_written(text);
    assert_eq!(written, expected);
}

#[test]
fn a_kept_frontmatter_without_a_final_line_feed_stays_as_it_was() {
    for text in [
        "---\nname: glossary\ndescription: Terms\n---",
        "---\r\nname: glossary\r\ndescription: Terms\r\n---",
        "---\nname: glossary\ndescription: Terms\n---\n",
        "---\n---",
        "---\nname: glossary\n---\n\nBody without a final line feed",
    ] {
        let (written, expected) = skill_md_written(text);
        assert_eq!(written, expected, "{text:?}");
    }
}
