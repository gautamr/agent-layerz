/// A layer of a fixture: its `layer.yaml` and its other files.
pub(crate) struct Layer {
    pub(crate) yaml: &'static str,
    pub(crate) files: &'static [(&'static str, &'static str)],
}

/// A file of the expected output: its path and its text.
pub(crate) type Golden = (&'static str, &'static str);

fn model(layers: &[Layer], options: &str) -> Merged {
    let found = merged_with(
        layers
            .iter()
            .map(|layer| layer_from_yaml(layer.yaml, layer.files))
            .collect(),
        options,
    );
    assert!(!found.diagnostics().has_errors(), "{}", found.diagnostics());
    found.merged().expect("no error was found").clone()
}

fn lines(found: &Diagnostics) -> Vec<String> {
    found.iter().map(ToString::to_string).collect()
}

fn path(text: &str) -> OutputPath {
    OutputPath::try_from(text).expect("a safe path")
}

/// Renders the stack and compares each golden file, and the paths the adapter made for these
/// three folders, byte for byte.
fn matches_expected(layers: &[Layer], options: &str, golden: &[Golden]) -> Emitted {
    let files = files_of(&model(layers, options));
    assert!(!files.diagnostics().has_errors(), "{}", files.diagnostics());
    let made: Vec<&str> = files.tree().paths().map(OutputPath::as_str).collect();
    let wanted: Vec<&str> = golden.iter().map(|(name, _)| *name).collect();
    assert_eq!(made, wanted);
    for (name, text) in golden {
        let file = files.tree().get(&path(name)).expect("a made file");
        assert_eq!(
            String::from_utf8_lossy(&file.bytes),
            *text,
            "{name} differs from the expected file"
        );
        assert_eq!(file.mode, FileMode::Regular, "{name}");
    }
    files
}

