#[test]
fn a_command_is_a_skill_only_the_user_can_call_and_a_script_keeps_its_executable_bit() {
    let merged = {
        let layer = layer_from_yaml(
            "name: only\nkind: repo\nvisibility: private\n",
            &[
                (
                    "commands/go.md",
                    "---\ndescription: Go\nargument_hint: <x>\n---\nDo it\n",
                ),
                (
                    "skills/s/SKILL.md",
                    "---\nname: s\ndescription: S\n---\nS body\n",
                ),
                ("skills/s/run.sh", "#!/bin/sh\n"),
            ],
        );
        let path = crate::path::SafeRelPath::try_from("skills/s/run.sh").expect("a path");
        let contents = layer.contents().clone().with_executable([path]);
        let layer = crate::stack::ResolvedLayer::new(
            layer.source().clone(),
            layer.meta().clone(),
            contents,
            None,
        );
        let found = crate::adapter_model::testing::merged_stack(vec![layer]);
        found.merged().expect("merged").clone()
    };
    let files = files_of(&merged);
    assert_eq!(
        text_of(&files, ".claude/skills/go/SKILL.md"),
        "---\n# GENERATED by agent-layerz \u{2014} DO NOT EDIT. Source: only:commands/go.md. Edit the source and run `alz build`.\nname: go\ndescription: Go\nargument-hint: <x>\ndisable-model-invocation: true\n---\n\nDo it\n"
    );
    assert_eq!(
        files
            .tree()
            .get(&path(".claude/skills/s/run.sh"))
            .expect("script")
            .mode,
        FileMode::Executable
    );
    assert_eq!(
        files
            .tree()
            .get(&path(".claude/skills/s/SKILL.md"))
            .expect("skill")
            .mode,
        FileMode::Regular
    );
}

