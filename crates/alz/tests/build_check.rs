//! `alz build` and `alz check` through the binary (spec §10.3 "`alz build`" and "`alz check`",
//! §13 item 14 "Non-destructive", TASK-55.9.9): the collision message and exit code with nothing
//! written, the summary line, the `--adopt` messages and the problem of a plan, and the lines
//! of `check` (`missing`, `differs from a fresh build`, `is stale`, `out of date`, the last line,
//! the exit codes and the rule that it writes nothing). Every run has its own home and cache and
//! works on a copy of `fixtures/14-non-destructive`.

// The tests sit in a `mod tests` so that `clippy::tests_outside_test_module` holds for this file
// as for every other one.
#[cfg(test)]
mod tests {
    use std::path::{Path, PathBuf};
    use std::time::Duration;

    use alz_test_support::{ScratchDir, copy_tree, read_tree};
    use assert_cmd::{Command, cargo::cargo_bin_cmd};

    struct Run {
        code: i32,
        stdout: String,
        stderr: String,
    }

    /// A copy of the fixture, with a home and a cache of its own.
    struct World {
        scratch: ScratchDir,
        repository: PathBuf,
    }

    impl World {
        fn new() -> Self {
            Self::of("14-non-destructive")
        }

        fn of(fixture: &str) -> Self {
            let scratch = ScratchDir::new().expect("a scratch directory");
            let fixture = Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("../../fixtures")
                .join(fixture);
            copy_tree(&fixture, &scratch.join("work")).expect("the fixture is copied");
            scratch.make_dirs("home").expect("made");
            Self {
                repository: scratch.join("work/repo"),
                scratch,
            }
        }

        /// The world after the hand-written agent was removed, so that the repository builds.
        fn buildable() -> Self {
            let world = Self::new();
            world
                .scratch
                .remove_file("work/repo/.claude/agents/foo.md")
                .expect("removed");
            world
        }

        fn alz(&self, arguments: &[&str]) -> Run {
            let mut command: Command = cargo_bin_cmd!("alz");
            let output = command
                .current_dir(&self.repository)
                .env_remove("CLAUDE_CONFIG_DIR")
                .env_remove("CODEX_HOME")
                .env("HOME", self.scratch.join("home"))
                .env("XDG_CACHE_HOME", self.scratch.join("cache"))
                .env("XDG_STATE_HOME", self.scratch.join("state"))
                .env("GIT_CONFIG_GLOBAL", "/dev/null")
                .env("GIT_CONFIG_NOSYSTEM", "1")
                .timeout(Duration::from_secs(60))
                .args(arguments)
                .output()
                .expect("alz runs and ends in time");
            Run {
                code: output.status.code().expect("an exit code"),
                stdout: String::from_utf8_lossy(&output.stdout).into_owned(),
                stderr: String::from_utf8_lossy(&output.stderr).into_owned(),
            }
        }

        /// Appends a line to the generated `AGENTS.md`, which keeps its generated marker.
        fn append_to_agents_file(&self) {
            let text = self
                .scratch
                .read_text("work/repo/AGENTS.md")
                .expect("AGENTS.md is read");
            self.scratch
                .write("work/repo/AGENTS.md", format!("{text}edited\n"))
                .expect("written");
        }

        fn tree(&self) -> std::collections::BTreeMap<String, alz_test_support::TreeFile> {
            read_tree(&self.repository).expect("the repository is read")
        }
    }

    const COLLISION: &str = "error [collision] .claude/agents/foo.md: exists and was not generated by agent-layerz; move it into a layer, or rerun with --adopt to move it into the repo layer\n";

    /// Spec §10.3 `alz build`, §13 item 14: a hand-written agent fails the build with the
    /// collision message and exit 1, and nothing is written.
    #[test]
    fn a_hand_written_agent_fails_the_build_with_the_collision_message_and_writes_nothing() {
        let world = World::new();
        let before = world.tree();
        let run = world.alz(&["build"]);
        assert_eq!(
            (run.code, run.stdout.as_str(), run.stderr.as_str()),
            (1, "", COLLISION)
        );
        assert_eq!(world.tree(), before);
    }

    /// Spec §10.3 `alz build`: a collision of a file in a state that is not alz's own is exit 1
    /// whatever else the build would write, so no generated file appears next to it.
    #[test]
    fn a_collision_leaves_no_generated_file_and_no_lock() {
        let world = World::new();
        let run = world.alz(&["build"]);
        assert_eq!(run.code, 1);
        for path in ["AGENTS.md", "CLAUDE.md", "layer.lock"] {
            assert!(!world.scratch.exists(format!("work/repo/{path}")), "{path}");
        }
    }

    /// Spec §10.3 `alz build`: on success it prints the summary line on standard output, with
    /// the counts of created, updated and deleted files, the targets and the visibility.
    #[test]
    fn a_build_prints_the_summary_line_with_the_counts_the_targets_and_the_visibility() {
        let world = World::buildable();
        let first = world.alz(&["build"]);
        assert_eq!(
            (first.code, first.stdout.as_str(), first.stderr.as_str()),
            (
                0,
                "built 2 files for claude: 2 created, 0 updated, 0 deleted (output visibility: private)\n",
                ""
            )
        );
        let again = world.alz(&["build"]);
        assert_eq!(
            again.stdout,
            "built 2 files for claude: 0 created, 0 updated, 0 deleted (output visibility: private)\n"
        );
        world.append_to_agents_file();
        let repaired = world.alz(&["build"]);
        assert_eq!(
            repaired.stdout,
            "built 2 files for claude: 0 created, 1 updated, 0 deleted (output visibility: private)\n"
        );
    }

    /// Spec §10.3 `alz build`: `--adopt` prints `adopted <from> → <to>` for each adopted file,
    /// and the build then runs again from the manifest (§13 item 14: the file moves into
    /// `.layer/agents/`).
    #[test]
    fn adopt_moves_the_hand_written_agent_into_the_layer_and_builds_again() {
        let world = World::new();
        let run = world.alz(&["build", "--adopt"]);
        assert_eq!(
            (run.code, run.stdout.as_str(), run.stderr.as_str()),
            (
                0,
                "adopted .claude/agents/foo.md → .layer/agents/foo.md\nbuilt 3 files for claude: 3 created, 0 updated, 0 deleted (output visibility: private)\n",
                ""
            )
        );
        assert!(world.scratch.exists("work/repo/.layer/agents/foo.md"));
        assert!(world.scratch.exists("work/repo/.claude/agents/foo.md"));
        assert_eq!(world.alz(&["check"]).code, 0);
    }

    /// Spec §10.3 `alz build`: a problem of the plan is `error [adopt] <problem>`, followed by
    /// `nothing was adopted; fix the problems above and rerun`, exit 1, and the repository is
    /// unchanged.
    #[test]
    fn an_adoption_problem_is_reported_and_nothing_is_adopted() {
        let world = World::new();
        world
            .scratch
            .write(
                "work/repo/.claude/agents/bad.md",
                "---\nname: bad\ndescription: x\npermissionMode: weird\n---\nbody\n",
            )
            .expect("written");
        let before = world.tree();
        let run = world.alz(&["build", "--adopt"]);
        assert_eq!(
            (run.code, run.stdout.as_str(), run.stderr.as_str()),
            (
                1,
                "",
                "error [adopt] .claude/agents/bad.md: unknown permissionMode 'weird'\nnothing was adopted; fix the problems above and rerun\n"
            )
        );
        assert_eq!(world.tree(), before);
    }

    /// Spec §10.3 `alz check`: a file that is missing and a file that differs are one line each,
    /// the last line says to run `alz build`, the exit code is 1 and nothing is written.
    #[test]
    fn check_names_a_missing_and_a_differing_file_and_writes_nothing() {
        let world = World::buildable();
        assert_eq!(world.alz(&["build"]).code, 0);
        world
            .scratch
            .remove_file("work/repo/CLAUDE.md")
            .expect("removed");
        world.append_to_agents_file();
        let before = world.tree();
        let run = world.alz(&["check"]);
        assert_eq!(
            (run.code, run.stdout.as_str(), run.stderr.as_str()),
            (
                1,
                "",
                "error [check] AGENTS.md: differs from a fresh build\nerror [check] CLAUDE.md: missing\ncheck failed: run `alz build` and commit the result\n"
            )
        );
        assert_eq!(world.tree(), before);
    }

    /// Spec §10.3 `alz check`: a file alz owns that the build no longer makes is `is stale`,
    /// and the lock that lists it is `out of date`.
    #[test]
    fn check_names_a_file_the_build_no_longer_makes_as_stale_and_the_lock_as_out_of_date() {
        let world = World::new();
        assert_eq!(world.alz(&["build", "--adopt"]).code, 0);
        world
            .scratch
            .remove_file("work/repo/.layer/agents/foo.md")
            .expect("removed");
        let before = world.tree();
        let run = world.alz(&["check"]);
        assert_eq!(
            (run.code, run.stdout.as_str(), run.stderr.as_str()),
            (
                1,
                "",
                "error [check] .claude/agents/foo.md: is stale\nerror [check] layer.lock: out of date\ncheck failed: run `alz build` and commit the result\n"
            )
        );
        assert_eq!(world.tree(), before);
    }

    /// Spec §10.3 `alz check`: a repository that was never built has every file missing and an
    /// outdated lock, and a collision prints as for `alz build`.
    #[test]
    fn check_prints_a_collision_as_build_does_and_ends_with_the_failed_line() {
        let world = World::new();
        let run = world.alz(&["check"]);
        assert_eq!(run.code, 1);
        assert_eq!(run.stdout, "");
        assert!(run.stderr.contains(COLLISION), "{}", run.stderr);
        assert!(
            run.stderr
                .contains("error [check] layer.lock: out of date\n"),
            "{}",
            run.stderr
        );
        assert!(
            run.stderr
                .ends_with("check failed: run `alz build` and commit the result\n"),
            "{}",
            run.stderr
        );
    }

    /// Spec §10.3 `alz check`: with nothing to report it prints `check passed: <n> generated
    /// files match the layers and the lock` on standard output, exits 0, and writes nothing.
    #[test]
    fn check_passes_with_the_count_of_generated_files_and_writes_nothing() {
        let world = World::buildable();
        assert_eq!(world.alz(&["build"]).code, 0);
        let before = world.tree();
        let run = world.alz(&["check"]);
        assert_eq!(
            (run.code, run.stdout.as_str(), run.stderr.as_str()),
            (
                0,
                "check passed: 2 generated files match the layers and the lock\n",
                ""
            )
        );
        assert_eq!(world.tree(), before);
    }

    /// Spec §13 item 15: files under `.claude/agent-memory/`, `backlog/`, `docs/` and `specs/`
    /// (and the configured `protected_paths`) are byte-identical before and after a build, even
    /// when a layer ships a file at the same path; the build warns about each one it left out.
    #[test]
    fn a_build_leaves_every_protected_path_byte_identical_and_warns_about_the_shipped_ones() {
        let world = World::of("15-protected-paths");
        let before = world.tree();
        let run = world.alz(&["build"]);
        assert_eq!(run.code, 0, "{}", run.stderr);
        assert!(run.stderr.contains("warning [protected]"), "{}", run.stderr);
        let after = world.tree();
        let protected = |path: &String| {
            [
                "backlog/",
                "docs/",
                "specs/",
                "notes/",
                ".claude/agent-memory",
                ".claude/settings.local.json",
            ]
            .iter()
            .any(|prefix| path.starts_with(prefix))
        };
        let kept = |tree: &std::collections::BTreeMap<String, alz_test_support::TreeFile>| {
            tree.iter()
                .filter(|(path, _)| protected(path))
                .map(|(path, file)| (path.clone(), file.clone()))
                .collect::<std::collections::BTreeMap<_, _>>()
        };
        assert!(!kept(&before).is_empty());
        assert_eq!(kept(&after), kept(&before));
    }
}
