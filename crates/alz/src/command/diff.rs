//! `alz diff` (spec §10.3): the change a build would make, as one unified diff for each file and
//! one for `layer.lock`. It makes no write.

use std::io::{self, Write};

use alz_core::render::diff::compare;
use alz_core::render::write_plan::{Change, Collision, Disk, Observed, lock_path};
use alz_core::{Code, Diagnostic, Diagnostics, Message, Stripped, Where};

use crate::command::Surroundings;
use crate::command::pipeline;
use crate::report::emit_diagnostics;

/// Runs `alz diff`: the diagnostics and the notes go to `stderr`, the patches to `stdout`, and
/// the exit code is 1 only when the build has an error.
pub fn run(surroundings: Surroundings<'_>, stdout: &mut impl Write, stderr: &mut impl Write) -> u8 {
    let repository = match pipeline::open_repository(surroundings) {
        Ok(repository) => repository,
        Err(diagnostic) => return emit_diagnostics(&Diagnostics::new().with(diagnostic), stderr),
    };
    let built = pipeline::compute(surroundings, &repository);
    let code = emit_diagnostics(&built.diagnostics, stderr);
    let Some(computed) = built.computed else {
        return code;
    };
    let (plan, disk) = match pipeline::plan_with_disk(&repository, &computed) {
        Ok(Some(planned)) => planned,
        Ok(None) => return code,
        Err(error) => {
            return emit_diagnostics(
                &Diagnostics::new().with(pipeline::write_failure(&error)),
                stderr,
            );
        }
    };
    let lock_patch = plan.lock_changed().then(|| {
        patch(
            lock_path().as_str(),
            &old_bytes(&disk, lock_path()),
            plan.lock_text().as_bytes(),
        )
    });
    let patches: Vec<String> = plan
        .changes()
        .iter()
        .map(|change| patch_of(change, &disk))
        .chain(lock_patch)
        .collect();
    let nothing_to_change = plan.changes().is_empty() && !plan.lock_changed();
    let notes = plan
        .collisions()
        .iter()
        .fold(Diagnostics::new(), |notes, collision| {
            notes.with(note_of(collision))
        });
    let printed = write_text(stdout, &patches.concat())
        .and_then(|()| write_text(stderr, &notes.to_string()))
        .and_then(|()| {
            if nothing_to_change {
                write_text(stdout, "no changes\n")
            } else {
                Ok(())
            }
        });
    printed.map_or(1, |()| code)
}

/// The diff of one change against what is on disk.
fn patch_of(change: &Change, disk: &Disk) -> String {
    let old = old_bytes(disk, change.path());
    match change {
        Change::Create { path, file } | Change::Update { path, file } => {
            patch(path.as_str(), &old, &file.bytes)
        }
        Change::Delete { path } => patch(path.as_str(), &old, &[]),
    }
}

fn patch(path: &str, old: &[u8], new: &[u8]) -> String {
    compare(old, new).render(&Stripped::from_untrusted(path))
}

/// The bytes at `path` when the writer saw a regular file, else nothing.
fn old_bytes(disk: &Disk, path: &alz_core::path::SafeRelPath) -> Vec<u8> {
    match disk.get(path) {
        Observed::Regular { bytes, .. } => bytes.clone(),
        Observed::Absent | Observed::Link | Observed::NotRegular | Observed::TooLarge => Vec::new(),
    }
}

/// The note `collision` for a path the build would refuse to overwrite.
fn note_of(collision: &Collision) -> Diagnostic {
    Diagnostic::note(
        Code::Collision,
        Some(Where::repository_file(Stripped::from_untrusted(
            collision.path().as_str(),
        ))),
        Message::new("is not generated by agent-layerz; alz build will refuse to overwrite it"),
    )
}

fn write_text(stream: &mut impl Write, text: &str) -> io::Result<()> {
    stream.write_all(text.as_bytes())?;
    stream.flush()
}
