// Regenerates the fixture that ties alz-core's stripped text (decision-26, class 1) to the
// TypeScript reference (src/core/sanitize.ts): every code point the reference removes, for the
// parity test. The Cf table itself is not generated; a test checks it against a vendored extract
// of the Unicode Character Database.
//
// Run from the repository root after `npm install`, and commit the output:
//
//   node crates/alz/tools/untrusted-code-points.mjs
//
// The Unicode version is the one of the Node.js that runs this script; it is written into the
// fixture, and must equal the version of the table (17.0).

import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const fixtureFile = "crates/alz-core/tests/fixtures/untrusted-code-points.txt";

const bundleDir = mkdtempSync(join(tmpdir(), "alz-sanitize-"));
const bundle = join(bundleDir, "sanitize.mjs");
execFileSync(
  "node_modules/.bin/esbuild",
  ["src/core/sanitize.ts", "--format=esm", `--outfile=${bundle}`, "--log-level=warning"],
  { stdio: "inherit" },
);
const { isControl, isFormat } = await import(pathToFileURL(bundle).href);

const SURROGATES = { first: 0xd800, last: 0xdfff };
const LAST_CODE_POINT = 0x10ffff;

/** The inclusive ranges of the code points (surrogates excluded) that satisfy the predicate. */
function rangesOf(predicate) {
  const ranges = [];
  for (let code = 0; code <= LAST_CODE_POINT; code += 1) {
    if (code >= SURROGATES.first && code <= SURROGATES.last) continue;
    if (!predicate(code)) continue;
    const last = ranges.at(-1);
    if (last && last[1] === code - 1) last[1] = code;
    else ranges.push([code, code]);
  }
  return ranges;
}

const hex = (code) => code.toString(16);
const removed = rangesOf((code) => isControl(code) || isFormat(String.fromCodePoint(code)));

const fixture = `# Every code point that isControl or isFormat of src/core/sanitize.ts removes, as inclusive
# hexadecimal ranges, surrogates excluded. Unicode ${process.versions.unicode}. Generated by
# crates/alz/tools/untrusted-code-points.mjs; do not edit.
${removed.map(([low, high]) => `${hex(low)} ${hex(high)}`).join("\n")}
`;
writeFileSync(fixtureFile, fixture);
