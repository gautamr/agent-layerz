import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { createTwoFilesPatch } from "diff";
import { isBinary } from "../../core/files";
import { LOCK_FILE } from "../../model/lock";
import { computeBuild } from "../../pipeline";
import { planWorkspace } from "../../render/workspace";
import { buildContext, type Io, printDiagnostics } from "../io";

/** `alz diff`: the change a pending build would make, as unified diffs. */
export function diffCommand(io: Io): number {
  const ctx = buildContext(io);
  const result = computeBuild(ctx);
  printDiagnostics(io, result.diags.items);
  if (result.diags.hasErrors) return 1;

  const plan = planWorkspace(ctx.repoRoot, result);
  const read = (path: string) => {
    const abs = join(ctx.repoRoot, path);
    return existsSync(abs) ? readFileSync(abs) : Buffer.alloc(0);
  };
  const show = (path: string, before: Buffer, after: Buffer) => {
    if (isBinary(before) || isBinary(after)) {
      io.stdout(`Binary file ${path} changes\n`);
      return;
    }
    io.stdout(
      createTwoFilesPatch(
        `a/${path}`,
        `b/${path}`,
        before.toString("utf8"),
        after.toString("utf8"),
      ),
    );
  };

  for (const change of plan.changes) {
    const after =
      change.kind === "delete"
        ? Buffer.alloc(0)
        : Buffer.from(result.tree.get(change.path)?.content ?? "");
    show(change.path, change.kind === "create" ? Buffer.alloc(0) : read(change.path), after);
  }
  if (plan.lockChanged) show(LOCK_FILE, read(LOCK_FILE), Buffer.from(plan.lockText));
  for (const path of plan.collisions) {
    io.stderr(
      `note: ${path} is not generated by agent-layerz; build will refuse to overwrite it\n`,
    );
  }
  if (plan.changes.length === 0 && !plan.lockChanged) io.stdout("no changes\n");
  return 0;
}
