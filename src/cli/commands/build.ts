import { applyAdoption, planAdoption } from "../../adopt";
import { ensureLocalIdentity, warnAboutIdentity } from "../../identity/setup";
import { computeBuild } from "../../pipeline";
import { planWorkspace } from "../../render/workspace";
import { applyPlan, syncGitignore } from "../../render/writer";
import { buildContext, type Io, plural, printDiagnostics } from "../io";

export function collisionMessage(path: string): string {
  return `error [collision] ${path}: exists and was not generated by agent-layerz; move it into a layer, or rerun with --adopt to move it into the repo layer\n`;
}

/** `alz build [--adopt]`: resolve, merge, render, write, update the lock. */
export function buildCommand(io: Io, options: { adopt: boolean }): number {
  const ctx = buildContext(io);
  let result = computeBuild(ctx);
  if (result.diags.hasErrors) {
    printDiagnostics(io, result.diags.items);
    return 1;
  }
  let plan = planWorkspace(ctx.repoRoot, result);

  if (plan.collisions.length > 0 && !options.adopt) {
    printDiagnostics(io, result.diags.items);
    for (const path of plan.collisions) io.stderr(collisionMessage(path));
    return 1;
  }
  if (options.adopt) {
    const adoption = planAdoption(ctx.repoRoot, result, plan.collisions);
    if (typeof adoption === "string") {
      io.stderr(`error [adopt] ${adoption}\n`);
      return 1;
    }
    for (const note of adoption.notes) io.stderr(`note [adopt] ${note}\n`);
    if (adoption.problems.length > 0) {
      for (const problem of adoption.problems) io.stderr(`error [adopt] ${problem}\n`);
      io.stderr("nothing was adopted; fix the problems above and rerun\n");
      return 1;
    }
    applyAdoption(adoption);
    for (const { from, to } of adoption.report) {
      io.stdout(
        `adopted ${from}${to.length > 0 ? ` → ${to.join(", ")}` : " (nothing left to keep)"}\n`,
      );
    }
    result = computeBuild(ctx);
    if (result.diags.hasErrors) {
      printDiagnostics(io, result.diags.items);
      return 1;
    }
    plan = planWorkspace(ctx.repoRoot, result);
    if (plan.collisions.length > 0) {
      for (const path of plan.collisions) io.stderr(collisionMessage(path));
      return 1;
    }
  }

  printDiagnostics(io, result.diags.items);
  applyPlan(ctx.repoRoot, result.tree, plan);
  syncGitignore(
    ctx.repoRoot,
    result.manifest.options.commitGenerated ? undefined : result.tree.paths(),
  );
  const declared = result.config.commitIdentity;
  const count = (kind: string) => plan.changes.filter((change) => change.kind === kind).length;
  io.stdout(
    `built ${plural(result.tree.paths().length, "file")} for ${result.manifest.targets.join(", ")}: ${count("create")} created, ${count("update")} updated, ${count("delete")} deleted (output visibility: ${result.lock.visibility})\n`,
  );
  // §9.4: --adopt (a setup command) adds the missing local identity; plain build only warns.
  if (declared && options.adopt) ensureLocalIdentity(ctx.repoRoot, declared, io.env, io);
  else if (declared) warnAboutIdentity(ctx.repoRoot, declared, io.env, io);
  return 0;
}
