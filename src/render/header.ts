/** Marker that identifies a file this tool generated. */
export const GENERATED_MARK = "GENERATED by agent-layerz";
/** The marker before the rename to agent-layerz; files that carry it still count as generated. */
export const LEGACY_GENERATED_MARK = "GENERATED by agent-layers";

/** §4.3 header text, without comment delimiters. */
export function headerText(sources: string[]): string {
  return `${GENERATED_MARK} — DO NOT EDIT. Source: ${sources.join(" + ")}. Edit the source and run \`alz build\`.`;
}

export function htmlHeader(sources: string[]): string {
  return `<!-- ${headerText(sources)} -->`;
}
