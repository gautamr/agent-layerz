import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { describe, expect, it } from "vitest";
import { referenceDrift } from "../drift";
import { tool } from "../exec";
import { fixture, layers, readFile, snapshot, type Workspace } from "../helpers";
import { sha256Hex } from "../spec/cache";

// Spec §4.3 "Which files are alz's own", "Links" and "What the writer compares": the writer
// overwrites or deletes only files that are alz's own, and a build that reports a collision
// writes nothing. Every case runs through `alz build`, in the fixture's `repo` folder.
const GENERATED_MARK = "GENERATED by agent-layerz";
const AGENT = ".claude/agents/foo.md";

const repoPath = (ws: Workspace, path: string): string => join(ws.root, "repo", path);

const write = (ws: Workspace, path: string, text: string): void => {
  mkdirSync(dirname(repoPath(ws, path)), { recursive: true });
  writeFileSync(repoPath(ws, path), text);
};

/** Writes a file of the personal layer, which lies beside the repository. */
const writePersonal = (ws: Workspace, path: string, text: string): void => {
  const target = join(ws.root, "personal", path);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, text);
};

/** The fixture after a first successful build, so that `repo/layer.lock` lists what it made. */
async function built(): Promise<Workspace> {
  const ws = fixture("39-writer-rules");
  expect((await layers(ws, "repo", ["build"])).code).toBe(0);
  return ws;
}

/** Records `path` in the lock's `files` with the hash of `text`, as a previous build would have. */
function lockFile(ws: Workspace, path: string, text: string): void {
  const lockPath = repoPath(ws, "layer.lock");
  const lock = JSON.parse(readFileSync(lockPath, "utf8")) as { files: Record<string, string> };
  lock.files[path] = `sha256:${sha256Hex(text)}`;
  writeFileSync(lockPath, JSON.stringify(lock));
}

describe("§4.3 what the writer overwrites and deletes", () => {
  referenceDrift(
    "TASK-55.6.7",
    "a file the lock lists, without the generated mark and with other bytes than the lock recorded, is a collision and keeps its bytes",
    async () => {
      const ws = await built();
      write(ws, AGENT, "HAND-EDITED\n");
      const before = snapshot(ws.root);
      const result = await layers(ws, "repo", ["build"]);
      expect(result.code).toBe(1);
      expect(result.stderr).toContain(AGENT);
      expect(readFile(ws, `repo/${AGENT}`)).toBe("HAND-EDITED\n");
      expect(snapshot(ws.root)).toEqual(before);
    },
  );

  it("a file the lock lists, without the generated mark and with the recorded bytes, is alz's own and is rewritten", async () => {
    const ws = await built();
    write(ws, AGENT, "PLAIN\n");
    lockFile(ws, AGENT, "PLAIN\n");
    const result = await layers(ws, "repo", ["build"]);
    expect(result.code).toBe(0);
    const agent = readFile(ws, `repo/${AGENT}`);
    expect(agent).toContain(GENERATED_MARK);
    expect(agent).toContain("Generated body.");
    expect((await layers(ws, "repo", ["check"])).code).toBe(0);
  });

  it("a link at a generated path is a collision and neither the link nor its target changes", async () => {
    const ws = fixture("39-writer-rules");
    write(ws, "notes.md", "NOTES\n");
    symlinkSync("notes.md", repoPath(ws, "AGENTS.md"));
    const before = snapshot(ws.root);
    const result = await layers(ws, "repo", ["build"]);
    expect(result.code).toBe(1);
    expect(result.stderr).toContain("AGENTS.md");
    expect(lstatSync(repoPath(ws, "AGENTS.md")).isSymbolicLink()).toBe(true);
    expect(readFile(ws, "repo/notes.md")).toBe("NOTES\n");
    expect(snapshot(ws.root)).toEqual(before);
  });

  referenceDrift(
    "TASK-55.6.7",
    "a generated path below a link is a collision and nothing is written through the link",
    async () => {
      const ws = fixture("39-writer-rules");
      mkdirSync(repoPath(ws, "elsewhere"));
      symlinkSync("elsewhere", repoPath(ws, ".claude"));
      const before = snapshot(ws.root);
      const result = await layers(ws, "repo", ["build"]);
      expect(result.code).toBe(1);
      expect(result.stderr).toContain(".claude");
      expect(snapshot(ws.root)).toEqual(before);
      expect(existsSync(repoPath(ws, "elsewhere/agents"))).toBe(false);
    },
  );

  const notRegular: [string, (ws: Workspace) => void][] = [
    ["a folder", (ws) => write(ws, "AGENTS.md/inside.txt", "INSIDE\n")],
    ["a FIFO", (ws) => void tool("mkfifo", [repoPath(ws, "AGENTS.md")])],
  ];
  for (const [kind, make] of notRegular) {
    referenceDrift(
      "TASK-55.6.7",
      `${kind} at a generated path is a collision and the build does not block`,
      async () => {
        const ws = fixture("39-writer-rules");
        make(ws);
        const before = snapshot(ws.root);
        const result = await layers(ws, "repo", ["build"]);
        expect(result.code).toBe(1);
        expect(result.stderr).toContain("AGENTS.md");
        expect(snapshot(ws.root)).toEqual(before);
      },
    );
  }

  referenceDrift(
    "TASK-55.6.7",
    "layer.yaml and a file under .layer/ that the lock lists with matching hashes are never deleted or overwritten",
    async () => {
      const ws = await built();
      const inputs = ["layer.yaml", ".layer/layer.yaml", ".layer/agents/foo.md"];
      for (const path of inputs) lockFile(ws, path, readFile(ws, `repo/${path}`));
      const before = Object.fromEntries(inputs.map((path) => [path, readFile(ws, `repo/${path}`)]));
      const result = await layers(ws, "repo", ["build"]);
      expect(result.code).toBe(0);
      for (const path of inputs) expect(readFile(ws, `repo/${path}`)).toBe(before[path]);
      expect(readFile(ws, `repo/${AGENT}`)).toContain("Generated body.");
    },
  );

  referenceDrift(
    "TASK-55.6.7",
    "a file the lock lists that the build no longer makes, and whose bytes are not the recorded ones, is never deleted",
    async () => {
      const ws = await built();
      write(ws, "old/stale.md", "EDITED BY HAND\n");
      lockFile(ws, "old/stale.md", "WHAT THE LOCK RECORDED\n");
      const result = await layers(ws, "repo", ["build"]);
      expect(result.code).toBe(0);
      expect(readFile(ws, "repo/old/stale.md")).toBe("EDITED BY HAND\n");
      expect(readFile(ws, "repo/layer.lock")).not.toContain("old/stale.md");
    },
  );

  referenceDrift(
    "TASK-55.6.7",
    "a passthrough file that differs from a generated file only in case is the error passthrough and the generated file is kept",
    async () => {
      const ws = fixture("39-writer-rules");
      writePersonal(ws, "settings.yaml", "claude:\n  cleanupPeriodDays: 30\n");
      expect((await layers(ws, "repo", ["build"])).code).toBe(0);
      const generated = readFile(ws, "repo/.claude/settings.json");
      expect(generated).toContain("cleanupPeriodDays");
      writePersonal(ws, "targets/claude/.claude/Settings.json", '{"hand": true}\n');
      const before = snapshot(ws.root);
      const result = await layers(ws, "repo", ["build"]);
      expect(result.code).toBe(1);
      expect(result.stderr).toContain(
        "error [passthrough] personal:targets/claude/.claude/Settings.json",
      );
      expect(readFile(ws, "repo/.claude/settings.json")).toBe(generated);
      expect(snapshot(ws.root)).toEqual(before);
    },
  );

  referenceDrift(
    "TASK-55.6.7",
    "a layer file at a case variant of a protected path is warned about as protected and is not written",
    async () => {
      const ws = fixture("39-writer-rules");
      writePersonal(ws, "targets/claude/Backlog/x.md", "FROM A LAYER\n");
      const result = await layers(ws, "repo", ["build"]);
      expect(result.code).toBe(0);
      expect(result.stderr).toContain("warning [protected] Backlog/x.md");
      expect(existsSync(repoPath(ws, "Backlog"))).toBe(false);
      expect(readFile(ws, "repo/layer.lock")).not.toContain("Backlog");
    },
  );

  it("a file under a managed folder that alz did not generate is never deleted", async () => {
    const fresh = fixture("39-writer-rules");
    write(fresh, ".claude/skills/mine/SKILL.md", "MINE\n");
    const freshBefore = snapshot(fresh.root);
    const first = await layers(fresh, "repo", ["build"]);
    expect(first.code).toBe(1);
    expect(first.stderr).toContain(".claude/skills/mine/SKILL.md");
    expect(snapshot(fresh.root)).toEqual(freshBefore);

    const ws = await built();
    write(ws, ".claude/rules/extra.md", "EXTRA\n");
    const result = await layers(ws, "repo", ["build"]);
    expect(result.code).toBe(1);
    expect(result.stderr).toContain(".claude/rules/extra.md");
    expect(readFile(ws, "repo/.claude/rules/extra.md")).toBe("EXTRA\n");
  });
});
