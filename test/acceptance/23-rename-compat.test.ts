import { rmSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { fixture, layers, readFile } from "../helpers";

describe("rename to agent-layerz", () => {
  it("files generated under the old name still count as generated", async () => {
    const ws = fixture("14-non-destructive");
    expect((await layers(ws, "repo", ["build", "--adopt"])).code).toBe(0);
    const path = `${ws.root}/repo/.claude/agents/foo.md`;
    writeFileSync(
      path,
      readFile(ws, "repo/.claude/agents/foo.md").replace("agent-layerz", "agent-layers"),
    );
    rmSync(`${ws.root}/repo/layer.lock`);
    const rebuild = await layers(ws, "repo", ["build"]);
    expect(rebuild.code).toBe(0);
    expect(readFile(ws, "repo/.claude/agents/foo.md")).toContain("GENERATED by agent-layerz");
  });

  it("replaces a .gitignore block written under the old name", async () => {
    const ws = fixture("14-non-destructive");
    expect((await layers(ws, "repo", ["build", "--adopt"])).code).toBe(0);
    const manifest = `${ws.root}/repo/layer.yaml`;
    writeFileSync(
      manifest,
      `${readFile(ws, "repo/layer.yaml")}options:\n  commit_generated: false\n`.replace(
        "options:\n  strict_slots: true\n",
        "",
      ),
    );
    writeFileSync(
      `${ws.root}/repo/.gitignore`,
      "node_modules/\n# >>> agent-layers generated (do not edit this block)\n/AGENTS.md\n# <<< agent-layers generated\n",
    );
    expect((await layers(ws, "repo", ["build"])).code).toBe(0);
    const gitignore = readFile(ws, "repo/.gitignore");
    expect(gitignore).not.toContain("agent-layers generated");
    expect(gitignore.match(/>>> agent-layerz generated/g)).toHaveLength(1);
    expect(gitignore).toContain("node_modules/\n");
  });
});
