import { describe, expect, it } from "vitest";
import { exists, fixture, layers, readFile } from "../helpers";

describe("§13.14 non-destructive", () => {
  it("a hand-written .claude/agents/foo.md fails the build with a clear message", async () => {
    const ws = fixture("14-non-destructive");
    const result = await layers(ws, "repo", ["build"]);
    expect(result.code).toBe(1);
    expect(result.stderr).toContain(".claude/agents/foo.md");
    expect(result.stderr).toContain("--adopt");
    expect(readFile(ws, "repo/.claude/agents/foo.md")).toContain("HAND-WRITTEN");
    expect(exists(ws, "repo/AGENTS.md")).toBe(false);
  });

  it("--adopt moves it into .layer/agents/ and builds", async () => {
    const ws = fixture("14-non-destructive");
    const original = readFile(ws, "repo/.claude/agents/foo.md");
    const result = await layers(ws, "repo", ["build", "--adopt"]);
    expect(result.code).toBe(0);
    expect(readFile(ws, "repo/.layer/agents/foo.md")).toBe(original);
    const generated = readFile(ws, "repo/.claude/agents/foo.md");
    expect(generated).toContain("GENERATED by agent-layerz");
    expect(generated).toContain("HAND-WRITTEN body.");
    expect((await layers(ws, "repo", ["check"])).code).toBe(0);
  });
});
